/**
 * Initializer
 * Condition
 * Increment or Decrement
*/

for (let i = 1; i <= 10 ; i++) {
    console.log(i);
}

// Sum

let sum = 0;

for (j = 0; j <= 10; j++){
    sum += j;
    console.log(j, sum);
}
console.log("Sum: ", sum);

// Reverse Sum
revSum = 0;

for (k = 10; k > 0; k--) {
    revSum += k;
}
console.log("Reverse Sum: ", revSum);